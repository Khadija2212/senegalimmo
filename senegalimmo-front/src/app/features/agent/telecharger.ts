/** Fait enregistrer un fichier reçu de l'API, par un lien d'objet temporaire. */
export function telecharger(document: Document, contenu: Blob, nom: string): void {
  const url = URL.createObjectURL(contenu);
  const lien = document.createElement('a');
  lien.href = url;
  lien.download = nom;
  document.body.appendChild(lien);
  lien.click();
  lien.remove();
  URL.revokeObjectURL(url);
}
